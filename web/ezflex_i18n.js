let _loc = null;

export function ezDetectLocale() {
  try {
    const v = window.localStorage.getItem('ezflex.locale');
    if (v === 'zh' || v === 'en') return v;
  } catch (_) {}
  try {
    const s = app && app.ui && app.ui.settings && app.ui.settings.getSettingValue;
    const v = s ? String(app.ui.settings.getSettingValue('Comfy.Locale') || '') : '';
    if (v) return v.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  } catch (_) {}
  try {
    return String((navigator.language || 'en')).toLowerCase().startsWith('zh') ? 'zh' : 'en';
  } catch (_) {}
  return 'en';
}

export function ezLocale() {
  if (!_loc) _loc = ezDetectLocale();
  return _loc;
}

